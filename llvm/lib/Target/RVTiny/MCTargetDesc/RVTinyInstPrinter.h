
#ifndef LLVM_LIB_TARGET_RVTINY_MCTARGETDESC_RVTINYINSTPRINTER_H
#define LLVM_LIB_TARGET_RVTINY_MCTARGETDESC_RVTINYINSTPRINTER_H

#include "RVTinyMCTargetDesc.h"
#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class RVTinyInstPrinter : public MCInstPrinter {
public:
  RVTinyInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                    const MCRegisterInfo &MRI)
    : MCInstPrinter(MAI, MII, MRI) {}

  void printRegName(raw_ostream &OS, MCRegister Reg) override;
  void printRegName(raw_ostream &OS, MCRegister Reg, unsigned AltIdx) const;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const;
  void printInstruction(const MCInst *MI, uint64_t Address,
                        const MCSubtargetInfo &STI, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address,
                       const MCSubtargetInfo &STI, raw_ostream &O);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address,
                               unsigned OpIdx, unsigned PrintMethodIdx,
                               const MCSubtargetInfo &STI, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);
  
  void printOperand(const MCInst *MI, int opNum, const MCSubtargetInfo &STI,
                    raw_ostream &OS);
  void printMemOperand(const MCInst *MI, int opNum, const MCSubtargetInfo &STI,
                       raw_ostream &OS);
  void printCCOperand(const MCInst *MI, int opNum, const MCSubtargetInfo &STI,
                      raw_ostream &OS);
  bool printGetPCX(const MCInst *MI, unsigned OpNo, const MCSubtargetInfo &STI,
                   raw_ostream &OS);
  void printMembarTag(const MCInst *MI, int opNum, const MCSubtargetInfo &STI,
                      raw_ostream &O);
  void printASITag(const MCInst *MI, int opNum, const MCSubtargetInfo &STI,
                   raw_ostream &O);
  void printPrefetchTag(const MCInst *MI, int opNum, const MCSubtargetInfo &STI,
                        raw_ostream &O);

};
} // end namespace llvm

#endif